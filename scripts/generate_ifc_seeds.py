def main():
    outdir = sys.argv[1] if len(sys.argv) > 1 else "ifc_seeds"
    os.makedirs(outdir, exist_ok=True)

    for name, gen in SEEDS.items():
        content = gen()
        # Add header/footer if not already present
        if not content.startswith("ISO-10303-21"):
            content = HEADER + content + FOOTER

        path = os.path.join(outdir, f"seed_{name}.ifc")
        with open(path, "w") as f:
            f.write(content)
        print(f"  {path} ({len(content)} bytes)")

    print(f"\nGenerated {len(SEEDS)} IFC seed files in {outdir}/")


if __name__ == "__main__":
    main()
