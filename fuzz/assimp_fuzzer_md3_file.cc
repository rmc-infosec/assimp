static const size_t head_md3_size = sizeof(head_md3_data);

static bool write_binary_file(const char *path, const void *data, size_t size) {
    FILE *fp = fopen(path, "wb");
    if (!fp) return false;
    fwrite(data, 1, size, fp);
    fclose(fp);
    return true;
}

extern "C" int LLVMFuzzerTestOneInput(const uint8_t *data, size_t dataSize) {
    if (!AssimpFuzz::IsValidSize(dataSize, "md3")) {
        return 0;
    }

    int pid = static_cast<int>(getpid());
    char dir_path[128];
    char lower_path[160], upper_path[160], head_path[160];
    char shader_path[160], lower_skin_path[160], upper_skin_path[160], head_skin_path[160];
    snprintf(dir_path, sizeof(dir_path), "/tmp/assimp_fuzz_md3_%d", pid);

    // Use "lower.md3" as the filename to trigger ReadMultipartFile()
    // The multipart code checks if filename (before last '_' or '.') is
    // "lower", "upper", or "head"
    snprintf(lower_path, sizeof(lower_path), "%s/lower.md3", dir_path);
    snprintf(upper_path, sizeof(upper_path), "%s/upper.md3", dir_path);
    snprintf(head_path, sizeof(head_path), "%s/head.md3", dir_path);
    snprintf(shader_path, sizeof(shader_path), "%s/lower.shader", dir_path);
    snprintf(lower_skin_path, sizeof(lower_skin_path), "%s/lower_default.skin", dir_path);
    snprintf(upper_skin_path, sizeof(upper_skin_path), "%s/upper_default.skin", dir_path);
    snprintf(head_skin_path, sizeof(head_skin_path), "%s/head_default.skin", dir_path);

    mkdir(dir_path, 0755);

    // Write fuzz input as lower.md3 (the primary file being fuzzed)
    if (!write_binary_file(lower_path, data, dataSize)) return 0;

    // Write valid companion files for multipart loading
    write_binary_file(upper_path, upper_md3_data, upper_md3_size);
    write_binary_file(head_path, head_md3_data, head_md3_size);

    // Write .skin files for all three parts
    static const char lower_skin[] = "l_legs,lower_texture\n";
    static const char upper_skin[] = "u_torso,upper_texture\n";
    static const char head_skin[] = "h_head,head_texture\n";
    write_binary_file(lower_skin_path, lower_skin, sizeof(lower_skin) - 1);
    write_binary_file(upper_skin_path, upper_skin, sizeof(upper_skin) - 1);
    write_binary_file(head_skin_path, head_skin, sizeof(head_skin) - 1);

    // Write a .shader file to exercise Q3Shader::LoadShader paths
    static const char shader_content[] =
        "default\n"
        "{\n"
        "  {\n"
        "    map default_texture\n"
        "    blendFunc GL_ONE GL_ONE\n"
        "    rgbGen identity\n"
        "    alphaFunc GT0\n"
        "    tcGen environment\n"
        "    depthWrite\n"
        "  }\n"
        "  cull none\n"
        "}\n"
        "lower_texture\n"
        "{\n"
        "  {\n"
        "    map lower_texture.tga\n"
        "    blendFunc GL_SRC_ALPHA GL_ONE_MINUS_SRC_ALPHA\n"
        "  }\n"
        "}\n";
    write_binary_file(shader_path, shader_content, sizeof(shader_content) - 1);

    Importer importer;
    if (!AssimpFuzz::ForceFormat(importer, "md3")) {
        goto cleanup;
    }

    // Set MD3-specific configs to exercise more paths
    if (dataSize >= 8) {
        importer.SetPropertyInteger(AI_CONFIG_IMPORT_MD3_KEYFRAME, data[6] % 5);
    }

    // Always enable multipart handling - the whole point of this fuzzer
    importer.SetPropertyInteger(AI_CONFIG_IMPORT_MD3_HANDLE_MULTIPART, 1);
    importer.SetPropertyBool(AI_CONFIG_IMPORT_MD3_LOAD_SHADERS, true);
    importer.SetPropertyString(AI_CONFIG_IMPORT_MD3_SHADER_SRC, dir_path);

    {
        unsigned int flags = 0;
        if (dataSize >= 8) {
            AssimpFuzz::ApplyImporterConfigs(importer, data, dataSize);
            flags = AssimpFuzz::GetProcessingFlags(data, dataSize);
        }
        importer.ReadFile(lower_path, flags);
    }

cleanup:
    unlink(lower_path);
    unlink(upper_path);
    unlink(head_path);
    unlink(shader_path);
    unlink(lower_skin_path);
    unlink(upper_skin_path);
    unlink(head_skin_path);
    rmdir(dir_path);
    return 0;
}
